"""
trees_to_csharp.py — compile the frozen XGBoost heads into plain C# (ADR 0018).

Why not ONNX in NinjaTrader: ONNX Runtime needs extra .NET/native DLLs added to
NT8 by hand, a common source of load failures. Depth-3 trees compile to a few
hundred KB of dependency-free C#, which NinjaScript builds like any other file.

Semantics reproduced exactly from the saved model JSON:
  * only the first best_iteration+1 trees (what XGBRegressor.predict uses)
  * comparisons in float32: go LEFT when (float)x < (float)threshold
  * NaN goes to the tree's default direction (default_left)
  * margin = base_score + sum(leaf values); the head's output is log1p(ticks),
    so ticks = expm1(margin)

Also writes a pure-Python evaluator over the same arrays and checks it against
xgboost on real rows; scripts/csharp_parity.py checks the compiled C# itself.

Usage:
  python -m model.trees_to_csharp --model-dir <paper_v1> --out ninjascript/NQBotV3Model.cs
"""
from __future__ import annotations
import argparse, json, os, re
import numpy as np

HEADS = {"Mfe": "mfe_head.xgb.json", "Mae": "mae_head.xgb.json"}


def load_trees(path):
    m = json.load(open(path))
    L = m["learner"]
    base = float(re.sub(r"[\[\]]", "", L["learner_model_param"]["base_score"]))
    best = int(L["attributes"]["best_iteration"])
    trees = L["gradient_booster"]["model"]["trees"][: best + 1]
    return base, trees


def f32(v: float) -> str:
    s = "%.9g" % np.float32(v)
    if "e" not in s and "." not in s and "inf" not in s and "nan" not in s:
        s += ".0"
    return s + "f"


def tree_expr(t, node=0) -> str:
    lc, rc = t["left_children"], t["right_children"]
    if lc[node] == -1:
        return f32(t["split_conditions"][node])
    fi = t["split_indices"][node]
    thr = f32(t["split_conditions"][node])
    dl = "true" if t["default_left"][node] else "false"
    cond = f"(float.IsNaN(x[{fi}]) ? {dl} : x[{fi}] < {thr})"
    return f"({cond} ? {tree_expr(t, lc[node])} : {tree_expr(t, rc[node])})"


def py_predict(base, trees, X):
    X = X.astype(np.float32)
    out = np.full(len(X), np.float32(base), dtype=np.float64)
    for t in trees:
        lc, rc, si, sc, dl = (t["left_children"], t["right_children"], t["split_indices"],
                              np.array(t["split_conditions"], dtype=np.float32), t["default_left"])
        for r in range(len(X)):
            n = 0
            while lc[n] != -1:
                v = X[r, si[n]]
                go_left = bool(dl[n]) if np.isnan(v) else (v < sc[n])
                n = lc[n] if go_left else rc[n]
            out[r] += float(sc[n])
    return out


def generate(model_dir, features, out_path, version):
    parts = []
    meta = {}
    for name, fn in HEADS.items():
        base, trees = load_trees(os.path.join(model_dir, fn))
        meta[name] = {"trees": len(trees), "base_score": base}
        lines = [f"            double s = {repr(base)};"]
        for t in trees:
            lines.append(f"            s += {tree_expr(t)};")
        body = "\n".join(lines)
        parts.append(f"""
        /// <summary>{name} head: returns log1p(ticks). {len(trees)} trees.</summary>
        public static double {name}Margin(float[] x)
        {{
{body}
            return s;
        }}

        /// <summary>{name} head in ticks: expm1(margin).</summary>
        public static double {name}Ticks(float[] x) {{ return Math.Exp({name}Margin(x)) - 1.0; }}
""")
    feat_list = ",\n            ".join(f'"{f}"' for f in features)
    code = f"""// <auto-generated> by model/trees_to_csharp.py — DO NOT EDIT BY HAND.
// NQ Bot v3 exit heads, {version}. Plain C#, no dependencies.
// Input: float[{len(features)}] in FeatureOrder. NaN = missing.
using System;

namespace NinjaTrader.NinjaScript.AddOns.NQBotV3
{{
    public static class NQBotV3Model
    {{
        public const string Version = "{version}";
        public const int NumFeatures = {len(features)};

        public static readonly string[] FeatureOrder = new string[]
        {{
            {feat_list}
        }};
{''.join(parts)}
    }}
}}
"""
    with open(out_path, "w", newline="\n") as fh:
        fh.write(code)
    return meta


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--model-dir", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    cfg = json.load(open(os.path.join(a.model_dir, "paper_config.json")))
    meta = generate(a.model_dir, cfg["feature_order"], a.out, cfg["version"])
    print(json.dumps(meta), "->", a.out, f"{os.path.getsize(a.out)/1024:.0f} KB")
